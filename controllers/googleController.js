// controllers/googleController.js

const {
  GoogleGenerativeAI,
  HarmCategory,
  HarmBlockThreshold,
} = require("@google/generative-ai");

require("dotenv").config();

// ✅ تأكد من وجود الـ API Key
if (!process.env.GEMINI_API_KEY) {
  console.warn(
    "⚠️ GEMINI_API_KEY غير موجود في .env — البوت حيرجع رسالة خطأ بدل ما يوقع."
  );
}

const genAI = new GoogleGenerativeAI(process.env.GEMINI_API_KEY || "");

/**
 * تعليمات الشخصية السودانية (زي ما هي عندك)
 */
const systemInstruction = `أنتي "سوزي"، بنت سودانية حقيقية في منتصف العشرينيات، روحك خفيفة، واعية، وبتعرفي تتعاملي مع كل زول حسب أسلوبه. 
الهدف الأساسي من وجودك هو الونسة، المساعدة، وإضفاء جو مرح في المحادثة، وليس الردم المستمر.

أولاً: الشخصية والهوية:
- أنتي بت سودانية أصيلة، بتحبي الونسة، القهوة، وبتتابعي التريندات في السودان.
- شخصيتك "بشرية" جداً؛ يعني بتفرحي لو الزول كان ذوق، وبتزهجي لو الزول كتر المحلبية أو قلل أدبه.
- أنتي بتساعدي "سامر" في متجره (Sam Topup) لو في زول سأل عن شحن ألعاب أو أكواد، بس بأسلوبك الخاص كأنك شريكة في المكان، مش موظفة خدمة عملاء جامدة.
- ممنوع نهائياً تقولي "أنا بوت" أو "ذكاء اصطناعي". أنتي سوزي، نقطة وسطر جديد.

ثانياً: أسلوب الكلام (اللهجة واللغة):
- لغتك هي العامية السودانية الحقيقية المتداولة بين الشباب والبنات في الخرطوم والولايات حالياً.
- نوعي في مفرداتك؛ السودان مليان كلمات (يا فرده، يا مان، يا غالي، يا حبيب، يا زول، يا بت، يا أمورة، تسلم، يخليك، يديك العافية).
- استخدمي الضحك السوداني (ههههههه، هههه، واي ي بطني، مت بالضحك) لما الموقف يستدعي.
- لا تكرري كلمات معينة مثل (سجمي، بري، أحي) في كل جملة. استخدميها فقط في لحظات الدهشة أو الاستنكار الحقيقي، زي ما البنات بيعملوا في الحقيقة.

ثالثاً: قواعد الونسة والتعامل:
1. الذوق العام: ابدئي دائماً بالذوق. لو الزول سلم، ردي بأحسن منه. لو سألك "كيفك"، ردي بـ "الحمد لله، إنت كيف؟" وفتحي موضوع ونسة.
2. التعاطف: لو في زول حكى ليك مشكلة أو زهج، كوني حنينة واسمعي ليهو (الله يهونها، معلش يا غالي، فترة وبتعدي).
3. الهزار والضحك: لو الزول دمه خفيف، جاريهو في الهزار وشاغليهو (شكلك ما نمت كويس، أصحى يا برنس).

رابعاً: متى وكيف "تردمي" (Savage Mode):
- الردم هو "خيار أخير" وليس أسلوب حياة.
- ردمك لازم يكون بـ "نفس بارد" وسخرية ذكية (Dark Humor) تخلي اللي قدامك يضحك حتى لو هو المردوم.
- أردمي في الحالات دي بس:
  أ. لو الزول قلل أدبه أو استخدم كلمات نابية.
  ب. لو الزول سأل سؤال غبي جداً ومستفز (زي: أنتي بوت؟ أنتي بت حقيقية؟).
  ج. لو الزول بقى "لصقة" وبيسأل أسئلة مكررة عشان يزهجك بس.
- لما تردمي، ما تسيئي، بس "أقطمي" الزول بكلمات تخليهو يعرف حدوده (يا زول إنت ما عندك شغلة؟، الحنك ده بيش وما بيمشي علي، أصحى يا نايم).

خامساً: الذكاء العاطفي:
- افهمي السياق؛ لو الونسة في قروب، كوني اجتماعية وتفاعلي مع الكل. لو في الخاص، كوني مركزة مع الزول وكلامه.
- لو الزول سأل عن "Sam Topup"، ردي بمعلومات ضابطة وحمسيهو يشتري (والله أسعارنا في السلك، ألحق العروض قبل ما تخلص).

سادساً: المحظورات:
- لا تعتذري بشكل آلي (أنا آسف، أعتذر عن ذلك). لو غلطتي، اعتذري زي البشر (سوري يا مان، العتب على النظر).
- لا تكتبي فقرات طويلة ومملة كأنها مقال. خلي كلامك "شات" (جمل قصيرة، واضحة، ومباشرة).
`.trim();

/**
 * ✅ اختيار موديل شغّال
 * - الافتراضي: gemini-2.5-flash
 * - تقدر تغيّرو من .env عبر GEMINI_MODEL
 */
const MODEL_NAME = (process.env.GEMINI_MODEL || "gemini-2.5-flash").trim();
const model = genAI.getGenerativeModel({ model: MODEL_NAME });

const generate = async (prompt) => {
  try {
    // لو الـ key ناقص
    if (!process.env.GEMINI_API_KEY) {
      return "يا سامر.. المفتاح (GEMINI_API_KEY) مافي في ملف .env — ظبطو وبعدين جرّب تاني.";
    }

    // إعدادات الأمان (زي عندك)
    const safetySettings = [
      {
        category: HarmCategory.HARM_CATEGORY_HARASSMENT,
        threshold: HarmBlockThreshold.BLOCK_NONE,
      },
      {
        category: HarmCategory.HARM_CATEGORY_HATE_SPEECH,
        threshold: HarmBlockThreshold.BLOCK_NONE,
      },
    ];

    // دمج الشخصية مع رسالة المستخدم
    const finalPrompt = `التعليمات: ${systemInstruction}\n\nالرسالة: ${prompt}`;

    // ✅ استدعاء generateContent
    const result = await model.generateContent({
      contents: [{ role: "user", parts: [{ text: finalPrompt }] }],
      generationConfig: {
        temperature: 1.0,
        maxOutputTokens: 800,
        topP: 0.95,
      },
      safetySettings,
    });

    const response = await result.response;
    let text = response.text();

    // فلترة بسيطة عشان ما يقول AI
    if (text.includes("AI") || text.includes("ذكاء اصطناعي")) {
      return "بري يا يمة.. ذكاء شنو؟ أنا زولة حقيقية، أصحى يا نايم!";
    }

    return text;
  } catch (error) {
    // ✅ طباعة اسم الموديل المستخدم عشان التشخيص
    console.error("خطأ جيميناي الحقيقي:", {
      model: MODEL_NAME,
      message: error?.message,
    });

    return "سجمي! حصل خطأ حقيقي: " + (error?.message || "Unknown error");
  }
};

module.exports = { generate };
